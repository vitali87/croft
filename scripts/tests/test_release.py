"""Tests for scripts/release.py: release notes written in PRs, versions assigned after merge.

Every PR used to bump `version` in Cargo.toml and write
`src/release_notes/<version>.md`. Every open PR then edited the same line, so
each merge put every other open PR in conflict, and a PR whose number main
reached had to move its version and rename its notes. Now a PR writes a
fragment, `src/release_notes/unreleased/<name>.md`, whose name no other PR
shares, and never touches the version. After a merge, `release.py cut` folds
the fragments into the next version's notes and bumps the version, once, on
main.

`check` is the PR gate and `cut` is what the version-bump workflow runs. Both
are pinned here in both directions: what they must accept as much as what they
must refuse.
"""

