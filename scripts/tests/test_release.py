import io
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import release  # noqa: E402

CI = ROOT / ".github" / "workflows" / "ci.yml"
VERSION_BUMP = ROOT / ".github" / "workflows" / "version-bump.yml"
PUBLISH_CRATE = ROOT / ".github" / "workflows" / "publish-crate.yml"
GATE_STEP = "Shipped changes add release notes and leave the version alone"
BUMP_STEP = "Fold the notes, bump the version and push"
SOURCE_STEP = "Check out the commit that set this version"
# What the steps run, copied into the throwaway repos they run in.
SCRIPTS = ["release.py", "next_version.py", "ships_nothing.py", "check_doc_ownership.py"]

CARGO_TOML = '''[package]
name = "croft-software"
version = "0.2.11"
edition = "2024"

[dependencies]
serde = { version = "0.2.11" }

[dependencies.toml]
version = "0.2.11"
'''

# The lockfile's own format line, a dependency that happens to share the
# version, and croft's stanza with a field between `name` and `version`, so a
# rewrite that matched the first `version` line, or assumed it follows `name`,
# would show.
CARGO_LOCK = '''# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "anstyle"
version = "0.2.11"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "croft-software"
source = "path+file:///work"
version = "0.2.11"
dependencies = [
 "anstyle",
]
'''

SHIPPED = "pub fn width(cols: u16) -> u16 {\n    cols / 2\n}\n"

README = "Unreleased notes: one file per change. See CONTRIBUTING.md.\n"


def with_anstyle(version: str) -> str:
    """CARGO_LOCK with its one dependency, anstyle, and only that, at `version`."""
    old = 'name = "anstyle"\nversion = "0.2.11"'
    new = f'name = "anstyle"\nversion = "{version}"'
    if old not in CARGO_LOCK:
        raise AssertionError("fixture anchor is stale")
    return CARGO_LOCK.replace(old, new)


def lockfile(*pinned: tuple[str, str]) -> str:
    """A lockfile pinning croft at 0.2.11 and each (name, version) given."""
    stanzas = [
        f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
        'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
        for name, version in pinned
    ]
    stanzas.append('[[package]]\nname = "croft-software"\nversion = "0.2.11"\n')
    return "version = 4\n\n" + "\n".join(stanzas)


def run(cwd, *args):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout


class Repo:
    """A throwaway croft-shaped repo on `main`, released at 0.2.11."""

    def __init__(self, tmp: Path):
        self.path = tmp
        run(tmp, "git", "init", "-q", "-b", "main")
        run(tmp, "git", "config", "user.email", "t@example.com")
        run(tmp, "git", "config", "user.name", "t")
        self.write("Cargo.toml", CARGO_TOML)
        self.write("Cargo.lock", CARGO_LOCK)
        self.write("src/lib.rs", SHIPPED)
        self.write("src/release_notes/0.2.11.md", "fix: The last release.\n")
        self.write("src/release_notes/unreleased/README.md", README)
        self.write("docs/GUIDE.md", "A guide.\n")
        self.commit()

    def write(self, name: str, text: str):
        path = self.path / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)

    def remove(self, name: str):
        (self.path / name).unlink()

    def read(self, name: str) -> str:
        return (self.path / name).read_text()

    def exists(self, name: str) -> bool:
        return (self.path / name).exists()

    def commit(self):
        run(self.path, "git", "add", "-A")
        run(self.path, "git", "commit", "-q", "-m", "c")

    def branch(self):
        run(self.path, "git", "checkout", "-q", "-b", "work")

    def check(self):
        """The gate's verdict on `work` against `main`: (errors, printed)."""
        out = io.StringIO()
        with redirect_stdout(out):
            errors = release.check("main", "HEAD", cwd=self.path)
        return errors, out.getvalue()

    def cut(self, kind="patch", released_lock=None):
        return release.cut(self.path, kind, released_lock)


def joined(errors):
    return "\n".join(errors)


class Check(unittest.TestCase):
    """The PR gate: a shipped change carries a fragment and leaves the version alone."""

    def test_a_shipped_change_with_a_fragment_passes(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Repo(Path(tmp))
            repo.branch()
            repo.write("src/lib.rs", SHIPPED.replace("/ 2", "/ 3"))
            repo.write("src/release_notes/unreleased/860-width.md", "fix: Width halves no more.\n")
            repo.commit()
            errors, _ = repo.check()
            self.assertEqual(errors, [])

    def test_a_shipped_change_without_a_fragment_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            repo = Repo(Path(tmp))
            repo.branch()
            repo.write("src/lib.rs", SHIPPED.replace("/ 2", "/ 3"))
            repo.commit()
            errors, _ = repo.check()
            self.assertIn("src/release_notes/unreleased/", joined(errors))

    def test_bumping_the_version_in_a_pr_fails(self):
        """The line every open PR used to fight over. The workflow assigns
        the version after merge, so a PR that sets one is refused even with a
        fragment."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = Repo(Path(tmp))
            repo.branch()
            repo.write("src/lib.rs", SHIPPED.replace("/ 2", "/ 3"))
            repo.write("Cargo.toml", CARGO_TOML.replace('version = "0.2.11"\nedition', 'version = "0.2.12"\nedition'))
            repo.write("src/release_notes/unreleased/860-width.md", "fix: Width.\n")
            repo.commit()
            errors, _ = repo.check()
            self.assertIn("0.2.11", joined(errors))
            self.assertIn("0.2.12", joined(errors))

    def test_writing_a_versions_notes_in_a_pr_fails(self):
        """A version's notes are written by `cut`, after merge. A PR that
        writes one, the old way, is pointed at a fragment instead."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = Repo(Path(tmp))
            repo.branch()
            repo.write("src/lib.rs", SHIPPED.replace("/ 2", "/ 3"))
            repo.write("src/release_notes/0.2.12.md", "fix: Width.\n")
            repo.commit()
            errors, _ = repo.check()
            self.assertIn("src/release_notes/0.2.12.md", joined(errors))

    def test_editing_a_released_versions_notes_fails(self):
        """A released version's notes describe a binary already out there."""
        with tempfile.TemporaryDirectory() as tmp:
            repo = Repo(Path(tmp))
            repo.branch()
