#!/usr/bin/env python3
"""Record the GIFs in README.md and docs/ from the real binary.

    cargo build && python3 scripts/demo/docs_gifs.py target/debug/croft [name ...]

With no names it records every scene into docs/images/<name>.gif. Each scene
runs on a fresh HOME, so croft opens on its default theme. Steps taken before
a scene's first `snap` (opening a file, hiding a bar) set the stage and are
not in the recording. Needs what tui_demo.py needs, plus git, cargo,
rust-analyzer and python3. Build from a clean checkout: a croft whose source
repo has moved on since it was built shows a rebuild hint in the status bar.
"""

from __future__ import annotations

import os
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "examples"))

import settings_editor  # noqa: E402
from tui_demo import Demo  # noqa: E402

OUT = HERE.parents[1] / "docs/images"
COLS, ROWS = 130, 32

# The word-count crate most scenes open: one commit on `main` with a TODO in
# each file, so blame, Search and Source Control all have something to show.
CARGO_TOML = """[package]
name = "wordcount"
version = "0.1.0"
edition = "2021"
"""
CARGO_LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "wordcount"
version = "0.1.0"
"""
MAIN_RS = """use std::collections::HashMap;

/// Count how often each word appears in `text`.
fn word_counts(text: &str) -> HashMap<&str, usize> {
    let mut counts = HashMap::new();
    for word in text.split_whitespace() {
        *counts.entry(word).or_insert(0) += 1;
    }
    counts
}

fn main() {
    // TODO: read the text from a file
    let text = "the quick brown fox jumps over the lazy dog";
    let counts = word_counts(text);
    let mut words: Vec<_> = counts.into_iter().collect();
    words.sort_by(|a, b| b.1.cmp(&a.1).then(a.0.cmp(b.0)));
    for (word, n) in words {
        println!("{word:>8} {n}");
    }
}
"""
TALLY_RS = """/// A word and how often it appeared.
pub struct Tally {
    pub word: String,
    pub count: usize,
}

impl Tally {
    // TODO: merge two tallies of the same word
    pub fn new(word: &str) -> Self {
        Tally { word: word.to_string(), count: 1 }
    }
}
"""
WORDCOUNT = {
    "Cargo.toml": CARGO_TOML,
    "Cargo.lock": CARGO_LOCK,
    ".gitignore": "/target\n",
    "src/main.rs": MAIN_RS,
    "src/tally.rs": TALLY_RS,
}

SHAPES_RS = """pub struct Circle {
    pub r: f64,
}

pub fn area(c: &Circle) -> f64 {
    std::f64::consts::PI * c.r * c.r
}

pub fn perimeter(c: &Circle) -> f64 {
    2.0 * std::f64::consts::PI * c.r
}

pub fn describe(c: &Circle) -> String {
    format!("r={} area={:.2}", c.r, area(c))
}
"""

STATS_PY = """def fib(n):
    a, b = 0, 1
    for i in range(n):
        a, b = b, a + b
    return a

def mean(xs):
    return sum(xs) / len(xs)

scores = [88, 92, 79, 95]
avg = mean(scores)
best = max(scores)
print(f"avg {avg:.1f}, best {best}")
grades = []
for s in scores:
    grades.append("A" if s >= 90 else "B")
if best > 100:
    print("impossible")
fib(12)
mean([])
"""


def demo(binary: str, files: dict[str, str], **kw) -> Demo:
    """A Demo at the docs' size whose commits are by `dev`."""
    d = Demo(binary, cols=COLS, rows=ROWS, files=files, **kw)
    (d.home / ".gitconfig").write_text(
        "[user]\n\tname = dev\n\temail = dev@example.com\n[init]\n\tdefaultBranch = main\n"
    )
    return d


def wordcount(binary: str) -> Demo:
    """A Demo on the word-count crate, committed as "Count words"."""
    d = demo(binary, dict(WORDCOUNT))
    # Your PATH, but the scene's HOME, so its .gitconfig names the author;
    # GIT_* variables (GIT_AUTHOR_NAME, GIT_DIR) would override it.
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env["HOME"] = str(d.home)
    for args in (["init", "-q"], ["add", "-A"], ["commit", "-q", "-m", "Count words"]):
        subprocess.run(["git", *args], cwd=d.project, env=env, check=True, capture_output=True)
    return d


def send(d: Demo, text: str) -> None:
    """Type `text` in one go, off camera."""
    d._tmux("send-keys", "-t", "demo", "-l", text)


def quietly(d: Demo, *keys: str, pause: float = 0.6) -> None:
    """Press tmux `keys` without recording a frame."""
    d.key(*keys)
    time.sleep(pause)


def run_command(d: Demo, query: str, shown: bool = True) -> None:
    """Run the Command Palette's top hit for `query`, on camera unless not `shown`."""
    d.ctrl_shift("p")
    if shown:
        d.snap(500)
        d.type(query, per_char_ms=60, hold_ms=700)
    else:
        time.sleep(0.5)
        send(d, query)
        time.sleep(0.6)
    d.key("Enter")
    if not shown:
        time.sleep(0.8)


def open_file(d: Demo, query: str, shown: bool = True) -> None:
    """Go to File (Ctrl+P), `query`, Enter."""
    d.key("C-p")
    if shown:
        d.snap(500)
        d.type(query, per_char_ms=80, hold_ms=600)
    else:
        time.sleep(0.5)
        send(d, query)
        time.sleep(0.6)
    d.key("Enter")
    if not shown:
        time.sleep(1.0)


def overview(binary: str, gif: Path) -> None:
    """Explorer, a Rust file with highlighting and inline blame, Go to File, cargo run."""
    with wordcount(binary) as d:
        d.start()
        d.snap(1800)
        open_file(d, "main")
        d.snap(3000)
        open_file(d, "tally")
        d.snap(2200)
        run_command(d, "focus terminal", shown=False)
        d.snap(300)
        d.type("cargo run -q", per_char_ms=70, hold_ms=500)
        d.key("Enter")
        time.sleep(6)
        d.snap(4000)
        d.save(gif)


def search(binary: str, gif: Path) -> None:
    """Find TODO across the workspace and open a hit at its line."""
    with wordcount(binary) as d:
        d.start()
        d.snap(1000)
        d.ctrl_shift("f")
        d.snap(600)
        d.type("TODO", per_char_ms=120, hold_ms=2500)
        d.key("Down")
        d.snap(800)
        d.key("Down")
        d.snap(900)
        d.key("Enter")
        d.snap(3500)
        d.save(gif)


def command_palette(binary: str, gif: Path) -> None:
    """Run Preferences: Color Theme and pick Tokyo Night, previewing on the way."""
    with wordcount(binary) as d:
        d.start()
        open_file(d, "main", shown=False)
        d.snap(1200)
        d.ctrl_shift("p")
        d.snap(1500)
        d.type("color theme", per_char_ms=70, hold_ms=1000)
        d.key("Enter")
        d.snap(1500)
        # Croft Loch is third; Tokyo Night is six rows down. Each row previews.
        for _ in range(6):
            d.key("Down")
            d.snap(500)
        d.snap(700)
        d.key("Enter")
        d.snap(3000)
        d.save(gif)


def customize_layout(binary: str, gif: Path) -> None:
    """Move the side bar right, hide and show the panel and the status bar."""
    with wordcount(binary) as d:
        d.start()
        open_file(d, "main", shown=False)
        d.snap(1200)
        run_command(d, "customize layout")
        d.snap(1500)
        # Rows: Activity Bar, Primary Side Bar, Secondary Side Bar, Panel,
        # Status Bar, Minimap, Auto-Hide Side Bar, then Left / Right. A
        # toggled row stays selected when the popup redraws.
        moves = [
            (["Down"] * 8, 2000),  # Primary Side Bar Position: Right
            (["Up"] * 5, 1600),  # Panel: hide
            (["Down"], 1600),  # Status Bar: hide
            ([], 1600),  # Status Bar: show
            (["Up"], 1600),  # Panel: show
            (["Down"] * 4, 2000),  # Primary Side Bar Position: Left
        ]
        for keys, hold in moves:
            for k in keys:
                d.key(k)
                d.snap(120)
            d.key("Enter")
            d.snap(hold)
        d.key("Escape")
        d.snap(1500)
        d.save(gif)


def symbol_tabs(binary: str, gif: Path) -> None:
    """Open perimeter as its own tab, edit it there, and see the edit in shapes.rs."""
    shapes = {
        "Cargo.toml": CARGO_TOML.replace("wordcount", "shapes"),
        "src/lib.rs": "pub mod shapes;\n",
        "src/shapes.rs": SHAPES_RS,
    }
    with demo(binary, shapes) as d:
        d.start()
        open_file(d, "shapes", shown=False)
        quietly(d, "Down", "Down", "Down", "Down", "Down", "Down", "Down", "Down", "Down")
        d.snap(1500)
        d.key("C-k")
        d.key("V")
        d.snap(2200)
        d.key("End")
        d.snap(300)
        d.type(" * 1.0 // full turn", per_char_ms=90, hold_ms=1500)
        open_file(d, "shapes")
        d.snap(3000)
        d.save(gif)


def terminal(binary: str, gif: Path) -> None:
    """Run a build, split a second pane, and the gutter dots marking each command's result."""
    with wordcount(binary) as d:
        d.start()
        run_command(d, "focus terminal", shown=False)
        d.snap(800)
        d.type("cargo build -q && echo built", per_char_ms=50, hold_ms=300)
        d.key("Enter")
        time.sleep(4)
        d.snap(1500)
        run_command(d, "split terminal")
        d.snap(1500)
        d.type("git log --oneline", per_char_ms=50, hold_ms=300)
        d.key("Enter")
        d.snap(1500)
        d.type("false", per_char_ms=80, hold_ms=300)
        d.key("Enter")
        d.snap(3000)
        d.save(gif)


def source_control(binary: str, gif: Path) -> None:
    """Open a changed file's diff against HEAD and commit it; the commit graph updates."""
    with wordcount(binary) as d:
        main_rs = MAIN_RS.replace(
            '    // TODO: read the text from a file\n'
            '    let text = "the quick brown fox jumps over the lazy dog";\n',
            '    let text = &std::fs::read_to_string("input.txt").unwrap_or_default();\n',
        ).replace("{word:>8}", "{word:>12}")
        (d.project / "src/main.rs").write_text(main_rs)
        d.start()
        d.snap(1000)
        d.ctrl_shift("s")
        d.snap(1500)
        d.key("Tab")
        d.snap(800)
        d.key("Enter")
        d.snap(2500)
        d.ctrl_shift("s")
        d.snap(600)
        d.type("Read the words from input.txt", per_char_ms=45, hold_ms=1000)
        d.key("Enter")
        time.sleep(1.5)
        d.snap(4000)
        d.save(gif)


def live_run(binary: str, gif: Path) -> None:
    """Values, output, errors and coverage painted beside the code as you type."""
    with demo(binary, {"stats.py": STATS_PY}) as d:
        d.start()
        open_file(d, "stats", shown=False)
        quietly(d, "C-b")
        quietly(d, "C-j")
        run_command(d, "toggle activity bar", shown=False)
        run_command(d, "toggle minimap", shown=False)
        d.snap(1800)
        d.key("C-k")
        d.key("v")
        time.sleep(2)
        d.snap(4500)
        # Into the brackets of `mean([])` on line 20.
        quietly(d, "C-End", "Home", *["Right"] * 6, pause=0.3)
        d.snap(900)
        d.type("1, 2", per_char_ms=180, hold_ms=300)
        time.sleep(1.5)
        d.snap(3500)
        d.key("End", "Enter")
        d.type("print(fib(30))", per_char_ms=120, hold_ms=300)
        time.sleep(2)
        d.snap(5000)
        d.save(gif)


def settings_editor_scene(binary: str, gif: Path) -> None:
    """examples/settings_editor.py, the Settings editor end to end."""
    settings_editor.main(binary, str(gif))


SCENES = {
    "overview": overview,
    "search": search,
    "command-palette": command_palette,
    "customize-layout": customize_layout,
    "symbol-tabs": symbol_tabs,
    "terminal": terminal,
    "source-control": source_control,
    "live-run": live_run,
    "settings-editor": settings_editor_scene,
}


def main(argv: list[str]) -> int:
    """Record the scenes `argv` names after the binary, or every scene."""
    if not argv:
        print(f"usage: docs_gifs.py <croft binary> [{' | '.join(SCENES)} ...]", file=sys.stderr)
        return 2
    binary, names = argv[0], argv[1:] or list(SCENES)
    unknown = [n for n in names if n not in SCENES]
    if unknown:
        print(f"unknown scene {', '.join(unknown)}; scenes: {', '.join(SCENES)}", file=sys.stderr)
        return 2
    OUT.mkdir(parents=True, exist_ok=True)
    for name in names:
        SCENES[name](binary, OUT / f"{name}.gif")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
